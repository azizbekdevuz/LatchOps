/* ---------------------------------------------------------------- Decision */

export function DecisionPanel({ detail, actor, onCall }: { detail: ReviewDetail; actor: PublicActor | null; onCall: Call }) {
  const { busy, error, run } = useAction();
  const alternatives = detail.snapshot.plan.alternatives;
  const [alternativeId, setAlternativeId] = useState(alternatives.find((a) => a.recommended)?.id ?? alternatives[0]?.id ?? '');
  const [reason, setReason] = useState('');
  const accepted = detail.explanations.find((e) => e.status === 'accepted');
  const latest = detail.decisions[0];
  const selfReview = actor?.id === detail.incident.requestedBy;
  const blockedReason = !actor
    ? 'Select an actor.'
    : actor.role !== 'approver'
      ? `Role "${actor.role}" cannot approve or reject (the server enforces this too).`
      : selfReview
        ? 'Four-eyes rule: the requester cannot decide their own review.'
        : null;

  const submit = (decision: 'approve' | 'reject') =>
    run(decision, () => onCall('decision', { decision, alternativeId, reason, explanationId: accepted?.id }));

  return (
    <Panel id="decision" title="Human decision" icon={<CheckCircle2 className="w-4 h-4 text-accent-blue" />}>
      {latest && (
        <div className={`rounded-lg border p-3 text-xs ${latest.decision === 'approve' ? 'border-accent-green/40' : 'border-accent-red/40'}`}>
          <p className="text-text-primary font-medium">
            {latest.decision === 'approve' ? `Approved ${latest.selectedAlternativeId}` : 'Rejected'} by {latest.actorId} ({latest.actorRole})
          </p>
          <p className="text-text-secondary mt-1">“{latest.reason}”</p>
          <p className="text-text-muted font-mono mt-1 text-[11px]">
            bound to evidence {short(latest.evidenceHash)} · expires {new Date(latest.expiresAt).toLocaleTimeString()} ·{' '}
            {latest.explanationId ? 'with accepted explanation' : 'without AI explanation'}
          </p>
        </div>
      )}
      {detail.incident.status === 'executed' ? (
        <p className="text-[11px] text-text-muted">The approved run has completed; this approval was single-use and the review is closed.</p>
      ) : (
        <>
          <fieldset className="space-y-2" disabled={busy !== null}>
            <legend className="text-xs text-text-secondary mb-1">Alternative (from the deterministic plan only)</legend>
            <div className="flex flex-wrap gap-2">
              {alternatives.map((alt) => (
                <label
                  key={alt.id}
                  className={`flex items-center gap-2 rounded-lg border px-3 py-1.5 text-xs cursor-pointer ${alternativeId === alt.id ? 'border-accent-green text-text-primary' : 'border-border-color text-text-secondary'}`}
                >
                  <input type="radio" name="alternative" className="accent-[#34e0a1]" checked={alternativeId === alt.id} onChange={() => setAlternativeId(alt.id)} />
                  {alt.title} <span className="font-mono text-text-muted">({alt.id})</span>
                </label>
              ))}
            </div>
            <textarea
              value={reason}
              onChange={(e) => setReason(e.target.value)}
              rows={2}
              placeholder="Written reason (required): which side is authoritative and why"
              aria-label="Decision reason"
              className="w-full bg-bg-tertiary border border-border-color rounded-lg p-2 text-xs text-text-primary"
            />
          </fieldset>
          {!accepted && <p className="text-[11px] text-accent-yellow">No accepted explanation: you are deciding on deterministic evidence alone. That is allowed and recorded.</p>}
          {blockedReason && <p className="text-[11px] text-text-muted">{blockedReason}</p>}
          <div className="flex gap-2">
            <button type="button" className="btn btn-primary" disabled={busy !== null || reason.trim().length < 5} onClick={() => submit('approve')}>
              {busy === 'approve' && <Loader2 className="w-4 h-4 animate-spin" />} Approve {alternativeId}
            </button>
            <button type="button" className="btn" disabled={busy !== null || reason.trim().length < 5} onClick={() => submit('reject')}>
              Reject
            </button>
          </div>
        </>
      )}
      <ErrorLine error={error} />
    </Panel>
  );
}

/* --------------------------------------------------------------- Execution */

interface ExecRow {
  display: string;
  exitCode: number;
  source: string;
}

export function ExecutionPanel({ detail, actor, onCall }: { detail: ReviewDetail; actor: PublicActor | null; onCall: Call }) {
  const { busy, error, run } = useAction();
  const latest = detail.executions[0];
  const result = latest?.result as
    | { verdict: string; reasons: string[]; execution: ExecRow[]; markerGuard: { checked: string[]; blocked: string[] }; verification: { changedSignals: Array<{ field: string; before: unknown; after: unknown }> } | null }
    | null;
  const auth = latest?.auth as { reasons: string[]; currentEvidenceHash: string | null } | undefined;

  return (
    <Panel
      id="run"
      title="Isolated recovery run"
      icon={<Terminal className="w-4 h-4 text-accent-yellow" />}
      aside={<span className="text-[11px] text-text-muted">temporary repository · no remotes · never pushes</span>}
    >
      <p className="text-xs text-text-secondary">
        The server rebuilds the incident in a fresh temp repository, re-hashes the evidence, and runs the deterministic authorization gate. Only commands from the
        approved plan alternative can run. The verdict comes from <code>verifyRecovery</code>, not from the explanation.
      </p>
      {detail.incident.source !== 'scenario' ? (
        <p className="text-xs text-accent-yellow">Imported CLI snapshots are review-only: nothing is ever executed against your repository.</p>
      ) : detail.incident.status === 'executed' ? null : (
        <button
          type="button"
          className="btn"
          disabled={busy !== null || !actor}
          onClick={() => run('exec', () => onCall('execute', {}))}
        >
          {busy === 'exec' ? <Loader2 className="w-4 h-4 animate-spin" /> : <Terminal className="w-4 h-4" />}
          Request isolated run
        </button>
      )}
      <ErrorLine error={error} />

      {latest && (
        <div className="space-y-3">
          <div className="flex flex-wrap items-center gap-3">
            <span className={`badge ${verdictClass(latest.verdict)} !text-sm !px-3 !py-1 font-mono`}>{latest.verdict}</span>
            <span className="text-[11px] text-text-muted font-mono">
              by {latest.actorId} · {latest.authorized ? 'authorized' : 'denied'} · {new Date(latest.createdAt).toLocaleTimeString()}
            </span>
          </div>
          {!latest.authorized && auth && (
            <ul className="rounded-lg border border-accent-yellow/40 p-3 text-xs space-y-1">
              {auth.reasons.map((r) => (
                <li key={r} className="text-accent-yellow flex gap-1.5">
                  <Lock className="w-3.5 h-3.5 shrink-0 mt-0.5" /> {r}
                </li>
              ))}
            </ul>
          )}
          {result && (
            <>
              {result.reasons.length > 0 && <p className="text-xs text-text-secondary">{result.reasons.join(' · ')}</p>}
              {result.markerGuard.checked.length > 0 && (
                <p className={`text-xs ${result.markerGuard.blocked.length ? 'text-accent-red' : 'text-accent-green'}`}>
                  Conflict-marker guard: {result.markerGuard.blocked.length ? `blocked ${result.markerGuard.blocked.join(', ')}` : `clean (${result.markerGuard.checked.length} file(s))`}
                </p>
              )}
              <div className="overflow-x-auto">
                <table className="w-full text-[11px] font-mono">
                  <thead className="text-text-muted text-left">
                    <tr>
                      <th className="py-1 pr-3">command</th>
                      <th className="py-1 pr-3">source</th>
                      <th className="py-1">exit</th>
                    </tr>
                  </thead>
                  <tbody>
                    {result.execution.map((row, i) => (
                      <tr key={`${row.display}-${i}`} className="border-t border-border-color">
                        <td className="py-1 pr-3 text-text-primary break-all">{row.display}</td>
                        <td className="py-1 pr-3 text-text-muted">{row.source}</td>
                        <td className={`py-1 ${row.exitCode === 0 ? 'text-accent-green' : 'text-accent-red'}`}>{row.exitCode}</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
              {result.verification && result.verification.changedSignals.length > 0 && (
                <ul className="text-[11px] font-mono text-text-secondary">
                  {result.verification.changedSignals.map((c) => (
                    <li key={c.field}>
                      {c.field}: {JSON.stringify(c.before)} → {JSON.stringify(c.after)}
                    </li>
                  ))}
                </ul>
              )}
            </>
          )}
        </div>
      )}
    </Panel>
  );
}

